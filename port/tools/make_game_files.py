#!/usr/bin/env python3
"""make_game_files.py - the launcher's list of the game's files (src/launcher/game_files.inc)

    tools/make_game_files.py <game folder> [src/launcher/game_files.inc] [--skip name ...]

Every file of a known-good NTSC-US game folder as {path, size, CRC-32}: hpcos_launcher.exe checks a player's game
folder against it after unpacking and on its first start (src/launcher/gamefiles.c), so a damaged or missing file is
named before the game runs instead of showing up as a silent fault in play (2026-10-29: a player's Burrow had no music
and nothing in the logs said why). The disc's files are byte-identical in every copy of this edition (Redump image,
trimmed xiso or a folder dump), so one list serves everyone.

Left out: files a disc does not carry that turn up in working folders (the recompiler's analysis, edited files' backups,
a disc image left in the folder), and with --skip files the port itself lets the player change (PoA's runtime.cfg,
which its trainer edits).
"""
import os
import sys
import zlib

SKIP_NAMES = {"default_analysis.json"}
SKIP_SUFFIXES = (".orig", ".part", ".bak", ".trainer-bak", ".iso", ".xiso")


def crc32(path):
    c = 0
    with open(path, "rb") as f:
        while chunk := f.read(1 << 22):
            c = zlib.crc32(chunk, c)
    return c


def main():
    args = sys.argv[1:]
    skip = set()
    while "--skip" in args:
        k = args.index("--skip")
        skip.add(args[k + 1].replace("/", "\\").lower())
        del args[k:k + 2]
    if not args:
        sys.exit(__doc__)
    root = args[0]
    out = args[1] if len(args) > 1 else os.path.join(os.path.dirname(__file__), "..", "src", "launcher",
                                                     "game_files.inc")
    if not os.path.isfile(os.path.join(root, "default.xbe")):
        sys.exit(f"{root} has no default.xbe: not a game folder")
    rows = []
    for d, dirs, files in os.walk(root):
        dirs.sort()
        for name in sorted(files):
            if name.lower() in SKIP_NAMES or name.lower().endswith(SKIP_SUFFIXES):
                continue
            p = os.path.join(d, name)
            rel = os.path.relpath(p, root).replace(os.sep, "\\")
            if rel.lower() in skip:
                continue
            rows.append((rel, os.path.getsize(p), crc32(p)))
    rows.sort(key=lambda r: r[0].lower())
    total = sum(r[1] for r in rows)
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by tools/make_game_files.py from a known-good NTSC-US game folder: do not edit.\n")
        f.write(f"// {len(rows)} files, {total} bytes. Path in the game folder, size in bytes, CRC-32 (zlib's).\n")
        for rel, size, c in rows:
            esc = rel.replace("\\", "\\\\")
            f.write(f'{{"{esc}", {size}u, 0x{c:08X}u}},\n')
    print(f"{out}: {len(rows)} files, {total / 1e9:.2f} GB")


if __name__ == "__main__":
    main()
